/**
 * check-biometric-poster-drift.mjs
 *
 * Visual regression guard for the biometric demo video.
 *
 * Uses FFmpeg to extract a key frame from the COMMITTED `public/biometric-demo.mp4`
 * at the canonical poster timestamp, then pixel-diffs it against a committed PNG
 * reference (`public/biometric-demo-poster-ref.png`).
 *
 * Why FFmpeg-based extraction:
 *   Browser-based screenshot capture of the animated demo is non-deterministic
 *   across sessions — Framer Motion, CSS animations, and video element playback
 *   all vary between runs even with synthetic clock control. Extracting a frame
 *   from the committed MP4 via FFmpeg is ALWAYS deterministic: the same MP4 byte-
 *   for-byte produces the exact same frame at a given timestamp.
 *
 * What this check catches:
 *   - Someone updates scene components and re-exports the MP4 but forgets to run
 *     `update:biometric-poster` to update the PNG reference (frame will differ).
 *   - Someone updates the PNG reference without re-exporting the MP4 (frame will differ).
 *   - The committed MP4 is corrupted or replaced with wrong content (frame will differ).
 *
 * What this check does NOT replace:
 *   The `biometric-video-drift` check (git-based) catches the more common case:
 *   sources changed but the MP4 itself was NOT re-exported. Both checks are
 *   complementary — the drift check is fast, the poster check is content-based.
 *
 * Reference management:
 *   public/biometric-demo-poster-ref.png  — committed PNG, generated by this
 *                                           script in --update-reference mode.
 *
 * Exit codes:
 *   0 — frame matches the reference within DIFF_THRESHOLD (no visual drift).
 *   1 — frame differs, FFmpeg not found, MP4 not found, or pipeline error.
 *
 * Usage:
 *   pnpm --filter @workspace/void-client run check:biometric-poster-drift
 *
 * Flags:
 *   --update-reference  Extract the key frame from the current committed MP4 and
 *                       overwrite public/biometric-demo-poster-ref.png.
 *                       Run this after re-exporting the MP4 and commit the result.
 *
 * Environment:
 *   POSTER_AT_S       Frame extraction timestamp in SECONDS (default: 12.3).
 *   DIFF_THRESHOLD    Max fraction of pixels allowed to differ (default: 0.01 = 1%).
 *
 * Wired into CI as the `biometric-poster-drift` validation workflow.
 */

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, copyFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const __dir = dirname(fileURLToPath(import.meta.url));
const CLIENT_ROOT = resolve(__dir, "..");

const POSTER_AT_S = Number(process.env.POSTER_AT_S || 12.3);
const DIFF_THRESHOLD = Number(process.env.DIFF_THRESHOLD || 0.01);

const MP4_PATH = resolve(CLIENT_ROOT, "public", "biometric-demo.mp4");
const REFERENCE_PNG = resolve(CLIENT_ROOT, "public", "biometric-demo-poster-ref.png");
const TMP_DIR = "/tmp/biometric-poster-check";
const EXTRACTED_PNG = resolve(TMP_DIR, "extracted-frame.png");

// ─── FFmpeg ──────────────────────────────────────────────────────────────────


function extractFrame(ffmpegBin, inputMp4, outputPng, timeS) {
  // -ss before -i uses keyframe seek (fast). -vframes 1 extracts exactly one frame.
  // -vsync 0 prevents frame duplication. Output is a lossless PNG.
  execFileSync(
    ffmpegBin,
    [
      "-y",
      "-ss", String(timeS),
      "-i", inputMp4,
      "-vframes", "1",
      "-vsync", "0",
      "-f", "image2",
      outputPng,
    ],
    { stdio: ["ignore", "ignore", "pipe"] },
  );
}

// ─── Pixel diff ──────────────────────────────────────────────────────────────

async function pixelDiff(pathA, pathB) {
  const [imgA, imgB] = await Promise.all([
    sharp(pathA).raw().toBuffer({ resolveWithObject: true }),
    sharp(pathB).raw().toBuffer({ resolveWithObject: true }),
  ]);

  const { width, height, channels } = imgA.info;
  let bufB = imgB.data;

  if (imgB.info.width !== width || imgB.info.height !== height) {
    console.warn(
      `[diff] reference is ${imgB.info.width}×${imgB.info.height}, ` +
        `extracted is ${width}×${height} — resizing reference for comparison.`,
    );
    bufB = await sharp(pathB).resize(width, height).raw().toBuffer();
  }

  const bufA = imgA.data;
  const totalPixels = width * height;

  // Both paths are PNG (lossless) so a per-channel tolerance is applied only
  // to absorb FFmpeg's YUV→RGB rounding (±2 per channel is typical).
  const CHANNEL_TOLERANCE = 3;
  let diffCount = 0;
  for (let i = 0; i < totalPixels * channels; i += channels) {
    let diff = false;
    for (let c = 0; c < channels; c++) {
      if (Math.abs(bufA[i + c] - bufB[i + c]) > CHANNEL_TOLERANCE) {
        diff = true;
        break;
      }
    }
    if (diff) diffCount++;
  }

  return { diffCount, totalPixels, fraction: diffCount / totalPixels };
}

// ─── Main ────────────────────────────────────────────────────────────────────

async function main() {
  const updateReference = process.argv.includes("--update-reference");

  if (!existsSync(MP4_PATH)) {
    console.error(`MP4 not found: ${MP4_PATH}`);
    console.error(
      "Export the biometric demo video first:\n" +
        "  node artifacts/biometric-demo-video/scripts/record-biometric.mjs\n" +
        "  cp /tmp/biometric-demo.mp4 artifacts/void-client/public/biometric-demo.mp4",
    );
    process.exit(1);
  }

  if (!updateReference && !existsSync(REFERENCE_PNG)) {
    console.error(`Reference PNG not found: ${REFERENCE_PNG}`);
    console.error(
      "Generate it from the current committed MP4:\n" +
        "  pnpm --filter @workspace/void-client run update:biometric-poster",
    );
    process.exit(1);
  }

  let ffmpeg;
  try {
    ffmpeg = execFileSync("which", ["ffmpeg"], { encoding: "utf8" }).trim();
    if (!ffmpeg || !existsSync(ffmpeg)) throw new Error("not found");
    console.log(`✓ ffmpeg: ${ffmpeg}`);
  } catch {
    console.error(
      "✗ ffmpeg not found. Install FFmpeg and ensure it is on PATH.",
    );
    process.exit(1);
  }

  mkdirSync(TMP_DIR, { recursive: true });

  console.log(
    `Extracting frame at t=${POSTER_AT_S}s from ${MP4_PATH} …`,
  );
  try {
    extractFrame(ffmpeg, MP4_PATH, EXTRACTED_PNG, POSTER_AT_S);
  } catch (err) {
    console.error("✗ FFmpeg frame extraction failed:", err.message);
    process.exit(1);
  }
  console.log(`✓ frame extracted: ${EXTRACTED_PNG}`);

  if (updateReference) {
    copyFileSync(EXTRACTED_PNG, REFERENCE_PNG);
    console.log(
      `✓ Reference PNG updated: ${REFERENCE_PNG}\n` +
        "  Commit this file alongside the re-exported MP4 so the reference stays current.",
    );
    process.exit(0);
  }

  console.log(`Comparing against committed reference: ${REFERENCE_PNG} …`);
  const { diffCount, totalPixels, fraction } = await pixelDiff(
    EXTRACTED_PNG,
    REFERENCE_PNG,
  );
  const pct = (fraction * 100).toFixed(2);
  const threshPct = (DIFF_THRESHOLD * 100).toFixed(2);

  if (fraction > DIFF_THRESHOLD) {
    console.error(
      `\n✗ Biometric poster frame mismatch!\n` +
        `  Differing pixels: ${diffCount.toLocaleString()} / ${totalPixels.toLocaleString()} (${pct}%)\n` +
        `  Threshold:        ${threshPct}%\n`,
    );
    console.error(
      "The committed MP4's frame at t=" +
        POSTER_AT_S +
        "s differs from the stored PNG reference.\n" +
        "Either the MP4 was re-exported without updating the reference, or the\n" +
        "reference was updated independently. Both files must be in sync.\n",
    );
    console.error(
      "If the MP4 was intentionally re-exported (scene change), update the reference:",
    );
    console.error(
      "  pnpm --filter @workspace/void-client run update:biometric-poster",
    );
    console.error("Then commit both files alongside the scene change.");
    console.error("");
    console.error(
      "If the MP4 has NOT been re-exported yet after a scene change, do so first:",
    );
    console.error("  1. Start the biometric-demo-video workflow (port 22687).");
    console.error(
      "  2. Run: node artifacts/biometric-demo-video/scripts/record-biometric.mjs",
    );
    console.error("  3. Copy outputs:");
    console.error(
      "       cp /tmp/biometric-demo.mp4 artifacts/void-client/public/biometric-demo.mp4",
    );
    console.error(
      "       ffmpeg -y -i /tmp/biometric-demo-poster.jpg -q:v 8 /tmp/poster-final.jpg",
    );
    console.error(
      "       cp /tmp/poster-final.jpg artifacts/void-client/public/biometric-demo-poster.jpg",
    );
    console.error(
      "  4. pnpm --filter @workspace/void-client run update:biometric-poster",
    );
    console.error("  5. Commit all four files alongside the scene change.");
    process.exit(1);
  }

  console.log(
    `✓ Biometric poster drift check passed: ${pct}% of pixels differ ` +
      `(threshold: ${threshPct}%, differing: ${diffCount.toLocaleString()}).`,
  );
  process.exit(0);
}

main();
